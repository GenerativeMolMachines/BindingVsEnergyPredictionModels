def top_p_decode_2(
    model, source, source_mask, tokenizer_tgt, max_len, device,
    top_p=0.9, temperature=1.0, repetition_penalty=1.2, min_tokens_to_keep=5
):
    sos_idx = tokenizer_tgt.token_to_id('[SOS]')
    eos_idx = tokenizer_tgt.token_to_id('[EOS]')

    assert sos_idx is not None and eos_idx is not None

    encoder_output = model.encode(source, source_mask)
    decoder_input = torch.full((1, 1), sos_idx, dtype=torch.long, device=device)

    generated_tokens = set()  # for repetition penalty

    for _ in range(max_len):
        decoder_mask = causal_mask(decoder_input.size(1)).type_as(source_mask).to(device)
        out = model.decode(encoder_output, source_mask, decoder_input, decoder_mask)
        logits = model.project(out[:, -1])

        # Temperature scaling
        logits = logits / temperature
        probs = torch.softmax(logits, dim=-1)

        # Apply repetition penalty
        for tok in generated_tokens:
            probs[0, tok] /= repetition_penalty

        # Sort and apply nucleus (top-p) filtering
        sorted_probs, sorted_indices = torch.sort(probs, descending=True)
        cumulative_probs = torch.cumsum(sorted_probs, dim=-1)

        cutoff = cumulative_probs > top_p
        cutoff[..., :min_tokens_to_keep] = False  # keep at least k tokens
        sorted_probs[cutoff] = 0.0
        sorted_probs /= sorted_probs.sum()

        # Sample next token
        next_token = sorted_indices[0, torch.multinomial(sorted_probs, 1).item()].item()
        generated_tokens.add(next_token)

        decoder_input = torch.cat(
            [decoder_input, torch.tensor([[next_token]], device=device)], dim=1
        )

        if next_token == eos_idx:
            break

    return decoder_input.squeeze(0)


def top_p_decode_3(
    model, source, source_mask, tokenizer_tgt, max_len, device,
    top_p=0.8, temperature=0.7, repetition_penalty=1.1, repetition_window=10
):
    """
    Generate DNA sequence (k-mer tokens) conditioned on protein input.
    
    Args:
        model: Transformer model with encode/decode/project methods.
        source: protein input tensor for encoder.
        source_mask: mask for encoder input.
        tokenizer_tgt: tokenizer for DNA k-mer tokens.
        max_len: maximum decoding length.
        device: torch device.
        top_p: nucleus sampling threshold.
        temperature: controls randomness; 1.0 = default, <1 sharp, >1 soft.
        repetition_penalty: penalize tokens repeated in the sliding window.
        repetition_window: number of recent tokens to consider for repetition penalty.
    """
    sos_idx = tokenizer_tgt.token_to_id('[SOS]')
    eos_idx = tokenizer_tgt.token_to_id('[EOS]')
    assert sos_idx is not None and eos_idx is not None

    encoder_output = model.encode(source, source_mask)
    decoder_input = torch.full((1, 1), sos_idx, dtype=torch.long, device=device)

    generated_tokens = []

    for _ in range(max_len):
        decoder_mask = causal_mask(decoder_input.size(1)).type_as(source_mask).to(device)
        out = model.decode(encoder_output, source_mask, decoder_input, decoder_mask)
        logits = model.project(out[:, -1])  # shape: [1, vocab_size]

        # Apply repetition penalty (sliding window)
        if repetition_penalty != 1.0 and generated_tokens:
            window = generated_tokens[-repetition_window:]
            for tok in set(window):
                if logits[0, tok] < 0:
                    logits[0, tok] *= repetition_penalty
                else:
                    logits[0, tok] /= repetition_penalty

        # Apply temperature
        probs = torch.softmax(logits / temperature, dim=-1)

        # Top-p (nucleus) filtering
        sorted_probs, sorted_indices = torch.sort(probs, descending=True)
        cumulative_probs = torch.cumsum(sorted_probs, dim=-1)
        sorted_probs[cumulative_probs > top_p] = 0.0

        # Handle edge case
        if sorted_probs.sum() == 0:
            sorted_probs = torch.ones_like(sorted_probs) / sorted_probs.numel()
        sorted_probs /= sorted_probs.sum()

        # Map back to original indices
        probs_filtered = torch.zeros_like(probs)
        probs_filtered[0, sorted_indices[0]] = sorted_probs[0]

        # Sample next token
        next_token = torch.multinomial(probs_filtered, 1).item()
        generated_tokens.append(next_token)

        # Append to decoder input
        decoder_input = torch.cat(
            [decoder_input, torch.tensor([[next_token]], device=device)], dim=1
        )

        if next_token == eos_idx:
            break

    return torch.tensor(generated_tokens, device=device)


